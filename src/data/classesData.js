export function getRearrangeContent(storyId, classId) {
  const story = rearrangeBank.find((item) => item.id === storyId);
  if (!story) return null;

  const sentenceCount = classSentenceCount[classId] || 8;
  const sentences = story.sentences.slice(0, sentenceCount);
  const correctOrder = story.correctOrder.filter((index) => index < sentenceCount);

  return {
    id: story.id,
    title: story.title,
    type: 'rearrange',
    sentences,
    correctOrder,
  };
}

