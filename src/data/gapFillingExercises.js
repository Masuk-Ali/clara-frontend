export function getRandomExercise(exercises = [], excludedId) {
  if (!exercises.length) return null;
  const candidates = exercises.length > 1 && excludedId !== undefined
    ? exercises.filter((exercise) => exercise.id !== excludedId)
    : exercises;
  const pool = candidates.length ? candidates : exercises;
  return pool[Math.floor(Math.random() * pool.length)];
}

